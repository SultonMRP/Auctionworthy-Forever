function Auctionworthy:AtlasRecipe(spellID)
	spellID = tonumber(spellID)
	if not spellID then
		return
	end
	local row = AuctionworthyAtlasRecipes and AuctionworthyAtlasRecipes[spellID]
	if type(row) ~= 'table' then
		return
	end
	return row
end

function Auctionworthy:AtlasReagents(spellID)
	local row = Auctionworthy:AtlasRecipe(spellID)
	if not row then
		return
	end
	local list = {}
	local i = 3
	while row[i] and row[i + 1] do
		local id = tonumber(row[i])
		local qty = tonumber(row[i + 1])
		if id and id > 0 and qty and qty > 0 then
			list[#list + 1] = { id = id, qty = qty }
		end
		i = i + 2
	end
	if #list == 0 then
		return
	end
	return list
end

local pendingAtlasIDs = {}

local function ItemNameByID(itemID)
	itemID = tonumber(itemID)
	if not itemID or itemID < 1 then
		return
	end
	if C_Item and C_Item.GetItemNameByID then
		local ok, name = pcall(C_Item.GetItemNameByID, itemID)
		if ok and type(name) == "string" and name ~= "" and not Auctionworthy:Secret(name) then
			return name
		end
	end
	if GetItemInfo then
		local ok, name = pcall(GetItemInfo, itemID)
		if ok and type(name) == "string" and name ~= "" and not Auctionworthy:Secret(name) then
			return name
		end
	end
end

local function RememberAtlasID(itemID)
	itemID = tonumber(itemID)
	if not itemID or itemID < 1 then
		return
	end
	local removed = AuctionworthyRemovedIDs
	if type(removed) == "table" and removed[itemID] then
		return
	end
	local name = ItemNameByID(itemID)
	if name then
		Auctionworthy:RememberMaterial(name, itemID)
		pendingAtlasIDs[itemID] = nil
		return true
	end
	pendingAtlasIDs[itemID] = true
	if C_Item and C_Item.RequestLoadItemDataByID then
		pcall(C_Item.RequestLoadItemDataByID, itemID)
	elseif GetItemInfo then
		pcall(GetItemInfo, itemID)
	end
end

function Auctionworthy:LearnAtlasItemNames()
	local have = Auctionworthy.NamedItemIDs and Auctionworthy:NamedItemIDs() or {}
	local recipes = AuctionworthyAtlasRecipes
	if type(recipes) ~= "table" then
		return
	end
	for _, row in pairs(recipes) do
		if type(row) == "table" then
			local created = tonumber(row[1])
			if created and created > 0 and not have[created] then
				RememberAtlasID(created)
			end
			local i = 3
			while row[i] do
				local id = tonumber(row[i])
				if id and id > 0 and not have[id] then
					RememberAtlasID(id)
					have[id] = true
				end
				i = i + 2
			end
		end
	end
end

local atlasNames = CreateFrame("Frame")
atlasNames:RegisterEvent("PLAYER_LOGIN")
atlasNames:RegisterEvent("GET_ITEM_INFO_RECEIVED")
atlasNames:SetScript("OnEvent", function(_, event, itemID, success)
	if event == "PLAYER_LOGIN" then
		Auctionworthy:LearnAtlasItemNames()
		return
	end
	if success == false then
		return
	end
	itemID = tonumber(itemID)
	if itemID and pendingAtlasIDs[itemID] then
		RememberAtlasID(itemID)
	end
end)
